/** 별칭 → 그룹. 정규화(소문자·공백제거) 키로 찾는다 — 'big bang' / 'BigBang' 같은 변형 흡수. */
const norm = (s: string) => s.toLowerCase().replace(/\s+/g, '');

const INDEX = new Map<string, string[]>();
for (const group of ALIAS_GROUPS) {
  for (const term of group) {
    const key = norm(term);
    // 한 단어가 두 그룹에 걸리면 동음이의 사고다 — 확장을 포기하는 게 오검색보다 낫다(계획서 4장)
    if (INDEX.has(key)) INDEX.set(key, []);
    else INDEX.set(key, group);
  }
}

/** 확장 상한 — 사전 실수 하나가 질의 한 건을 수십 번의 DB 왕복으로 만들지 않도록. */
export const EXPAND_MAX = 8;

/**
 * 질의를 동의어로 넓힌다. 원본이 항상 첫 번째(결과 순서에서 원본 일치가 우선돼야 한다).
 * 별칭이 없으면 원본 하나만 담긴 배열을 돌려준다.
 */
export function expandQuery(raw: string): string[] {
  const q = raw.trim();
  if (!q) return [];
  const group = INDEX.get(norm(q));
  if (!group?.length) return [q];
  const out = [q];
  for (const t of group) {
    if (out.length >= EXPAND_MAX) break;
    if (norm(t) !== norm(q)) out.push(t);
  }
  return out;
}
