export function getDeck(id: string): Deck | undefined {
	return DECKS.find((d) => d.id === id);
}

/**
 * 덱의 실제 문체(§4 CLT). 덱별 `penaltyStyleOverride`가 있으면 그것,
 * 없으면 유형 기본값 `TYPE_CONFIG[type].penaltyStyle`. UI 레이아웃 분기(Phase 4)가 소비.
 */
export function penaltyStyleOf(deck: Deck): PenaltyStyle {
	return deck.penaltyStyleOverride ?? TYPE_CONFIG[deck.type].penaltyStyle;
}

/**
 * 아이콘/이모지 필드가 업로드 이미지인지(URL·data URI) 판별.
 * true면 `<img>`로, false면 이모지 글자로 렌더(Icon.svelte). 하위호환: 기존 이모지 덱은 그대로 글자.
 */
export function isImageIcon(v: string | undefined | null): boolean {
	return !!v && /^(https?:\/\/|data:image\/)/.test(v);
}

/**
 * 결과 영수증 항목용 자동 축약. `penalty.short`가 없을 때 폴백.
 * 음슴체 종결 꼬리(~해야 함/~임 등)를 떼고, 그래도 길면 앞부분만 남기고 …로 마무리.
 * (품질은 손저작 short만 못하니, 영수증을 알차게 하려면 short를 채우는 게 정석.)
 */
export function shortenPenalty(text: string): string {
	let s = text.trim();
	// 음슴체 종결부 제거
	s = s
		.replace(/\s*(해야|여야|어야|아야|이어야|되어야|돼야|봐야|받아야)?\s*함$/, '')
		.replace(/\s*(임|음|됨)$/, '')
		.trim();
	if (s.length > 18) s = s.slice(0, 17).trim() + '…';
	return s || text.trim();
}
