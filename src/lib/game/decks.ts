/**
 * 주제 유형(docs/game-topic-types.md v2 §2). 유저가 선택 대상과 맺는 심리적 관계.
 * 이 태그가 문체 길이·결과 프레이밍·UI를 분기시킨다(§10-①).
 */
export type DeckType = 'attribute' | 'person' | 'scenario' | 'acquisition' | 'value';

/** 페널티 문체 기본 길이(§5-3). 짧은 조건 vs 긴 에피소드. */
export type PenaltyStyle = 'short' | 'long';

/** 결과 카드 프레이밍 키(§9 결과 프레이밍 행). Phase 1에서 verdictLine 분기에 사용. */
export type ResultFraming = 'preference' | 'tolerance' | 'strategy' | 'desire' | 'values';

/**
 * 결과 해석 모드(§3 결과 로직 충돌).
 * - `preference`: 현시선호. 버틴 깊이=진짜 취향, 잦은 스위치=결정장애(속성/인물/획득/가치).
 * - `strategy`: 전략 스타일. 스위치=상황 재계산이지 포기가 아님 → 잦은 스위치=적응형(상황형).
 */
export type ResultMode = 'preference' | 'strategy';

export interface TypeConfig {
	framing: ResultFraming;
	penaltyStyle: PenaltyStyle;
	resultMode: ResultMode;
}

/**
 * 유형별 기본 설정. 결과 로직·문체·프레이밍이 여기서 갈린다.
 * 덱별로 `penaltyStyleOverride`가 penaltyStyle을 덮어쓸 수 있다(§4 CLT 오버라이드).
 */
export const TYPE_CONFIG: Record<DeckType, TypeConfig> = {
	attribute: { framing: 'preference', penaltyStyle: 'short', resultMode: 'preference' },
	person: { framing: 'tolerance', penaltyStyle: 'long', resultMode: 'preference' },
	scenario: { framing: 'strategy', penaltyStyle: 'short', resultMode: 'strategy' }, // 중간 길이(≤25자)
	acquisition: { framing: 'desire', penaltyStyle: 'short', resultMode: 'preference' }, // 중간~짧(부작용형)
	value: { framing: 'values', penaltyStyle: 'short', resultMode: 'preference' }
};

export interface Penalty {
	/** 붙는 판 번호 = 강도 (2~10) */
	strength: number;
	/** "그런데 이제 ___" 뒤에 붙는 짧은 조건. 설명 말고 조건만(예: "히터 없음", "외투 1개뿐") */
	text: string;
	/**
	 * 결과 영수증 항목용 짧은 라벨(선택, v3.1). 예: "축의금 5만원 궁상".
	 * 없으면 text를 자동 축약(shortenPenalty). 게임 보드엔 항상 원문 text.
	 */
	short?: string;
	/**
	 * v3 메리트 결합(docs/v3-pivot §2-1). 있으면 렌더 "그런데 이제 {text}. 하지만 {merit}."
	 * 같은 도메인 인과 파생 + 페널티 감정 ≥ 메리트 ×2 + 컨셉 배신 금지 + 3초 저울질.
	 * 없으면 v2 페널티-온리로 렌더(기존 덱 호환).
	 */
	merit?: string;
	/**
	 * 바구니 "🎁 얻은 것" 칩용 짧은 라벨(선택, v3.1). merit의 축약판. 예: "평일 늦잠 꿀맛".
	 * 없으면 merit을 자동 축약(shortenPenalty). short가 페널티용이면 이건 메리트용.
	 */
	meritShort?: string;
}

/**
 * v3 결과 캐릭터 카드(docs/v3-pivot §2-2). 편·결과(극단/애매)별로 하나.
 * 공유 가능한 유형 라벨 하나. (특이 스탯·예언은 렌더 안 되어 제거됨.)
 */
export interface ResultCard {
	/** 유형 네이밍 = 명사구 라벨. 한눈에 이해되고 웃기게, 편 이름으로 끝냄(예: "좋아요 없으면 못 사는 관종"). */
	label: string;
}

/** 한 편의 캐릭터 카드 2종: 극단(강도 8+까지 우세) / 애매(강도 5~7 전환). */
export interface SideResultCards {
	extreme: ResultCard;
	mild: ResultCard;
}

/** 덱의 v3 캐릭터 카드(편별 극단/애매). 있으면 결과를 캐릭터 카드로 렌더, 없으면 v2 버틴깊이. */
export interface DeckResultCards {
	a: SideResultCards;
	b: SideResultCards;
}

export interface Side {
	name: string;
	emoji: string;
	/**
	 * v2 완화책(탈출구). 이 편을 고르면 상시 적용, 1판 자리에 "그래도 ~"로 노출.
	 * ⚠️ v3는 메리트를 각 Penalty에 결합(Penalty.merit)하는 방향 — 이 필드는 v2 덱 호환용.
	 */
	merit?: string;
	/** 강도 2~10 순서대로 9장 */
	penalties: Penalty[];
}

export interface Deck {
	id: string;
	title: string;
	icon: string;
	/** 주제 유형(§2). 문체·결과 프레이밍·UI 분기의 기준. */
	type: DeckType;
	/** 유형 기본 문체를 덮어쓰는 덱별 오버라이드(§4 CLT). 없으면 TYPE_CONFIG[type] 사용. */
	penaltyStyleOverride?: PenaltyStyle;
	a: Side;
	b: Side;
	/** v3 캐릭터 카드(편별 극단/애매). 있으면 결과를 캐릭터 카드로 렌더. */
	resultCards?: DeckResultCards;
}

/** 강도 2~10 텍스트 배열을 Penalty[]로 (인덱스 0 = 강도 2) */
function pens(texts: string[]): Penalty[] {
	return texts.map((text, i) => ({ strength: i + 2, text }));
}

/** v3: [페널티, 메리트] 9쌍을 강도 2~10 Penalty[]로. */
function pensM(pairs: [text: string, merit: string][]): Penalty[] {
	return pairs.map(([text, merit], i) => ({ strength: i + 2, text, merit }));
}

/** [페널티, 영수증 short] 쌍을 강도 2~10 Penalty[]로. 메리트 없는 순수 페널티 + 손저작 축약 라벨. */
function pensS(pairs: [text: string, short: string][]): Penalty[] {
	return pairs.map(([text, short], i) => ({ strength: i + 2, text, short }));
}

